#!/usr/bin/env python3
"""Compare the pre-audit dataset with the revised-protocol dataset.

Reads the archived pre-audit processed metrics and the new processed metrics,
and produces a methodology-change report:

- configurations whose conclusions changed (mean throughput/latency moved
  outside the old range)
- configurations whose conclusions remained stable
- configurations with substantially increased variance
- configurations that were previously under-sampled (n < 10)
- configurations whose previous results cannot be considered reliable
  (methodological problems: non-randomized order, fixed seed, warm-up
  included in resources, unmeasured elections)

The report uses precise language ("insufficiently sampled", "not
independently isolated", "methodology changed", "result was not reproduced
under the revised protocol"). It never frames old results as "wrong" without
evidence.

Usage:
    python3 report/compare_datasets.py \
        --old results/archive/pre-audit-2026-09-19/processed \
        --new results/processed \
        --out results/methodology-change-report.md
"""
import argparse
import csv
import json
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stats as labstats


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def fnum(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def config_key(m):
    """Configuration identity. The experiment family is part of the key:
    workload, concurrency, conflict (at conflict_pct 0) and scaling-r3 share
    every numeric parameter, so grouping without the family merges four
    different experiments. The archived dataset predates the experiment
    column and encodes the family as the run-ID prefix.
    """
    fam = m.get("experiment") or m.get("run_id", "").split("-")[0]
    return (fam, m.get("protocol"), m.get("replicas"), m.get("read_pct"),
            m.get("write_pct"), m.get("concurrency"), m.get("conflict_pct"),
            m.get("failure_mode"), m.get("failed_elections_target", 0))


def group(rows):
    out = defaultdict(list)
    for r in rows:
        out[config_key(r)].append(r)
    return out


def summarize(vals):
    vals = [v for v in vals if v is not None]
    return {
        "n": len(vals),
        "mean": labstats.mean(vals),
        "median": labstats.median(vals),
        "sd": labstats.stdev(vals),
        "ci95_lo": labstats.ci95(vals)[0],
        "ci95_hi": labstats.ci95(vals)[1],
    }


def fmt(v, nd=1):
    if v is None:
        return "N/A"
    return f"{v:.{nd}f}"


def config_label(key):
    exp, proto, replicas, rp, wp, conc, conflict, fmode, ftarget = key
    # The family is part of the label: several families share the same numeric
    # parameters (workload, concurrency, conflict x0, scaling r3).
    label = f"{exp}/{proto}/r{replicas}/w{wp}/c{conc}"
    if conflict:
        label += f"/x{conflict}"
    if fmode and fmode != "none":
        label += f"/{fmode}"
        if fmode == "election":
            label += f"/e{ftarget}"
    return label


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", required=True, help="pre-audit processed dir")
    ap.add_argument("--new", required=True, help="revised processed dir")
    ap.add_argument("--out", default="results/methodology-change-report.md")
    args = ap.parse_args()

    old_metrics = read_csv(os.path.join(args.old, "metrics.csv"))
    new_metrics = read_csv(os.path.join(args.new, "metrics.csv"))
    # The revised dataset is compared under its own selection rule (one
    # observation per planned repetition, host-contaminated runs excluded), so
    # the comparison is not biased by runs the revised protocol rejects.
    new_metrics = [m for m in new_metrics if str(m.get("included", "1")) == "1"]
    old_groups = group(old_metrics)
    new_groups = group(new_metrics)

    lines = []
    lines.append("# Methodology-Change Report")
    lines.append("")
    lines.append("Comparison of the pre-audit dataset "
                 "(`results/archive/pre-audit-2026-09-19/`) with the "
                 "revised-protocol dataset. Generated by "
                 "`report/compare_datasets.py` from the raw per-run "
                 "observations; no values are hardcoded.")
    lines.append("")
    lines.append(f"- Pre-audit runs: {len(old_metrics)}")
    lines.append(f"- Revised runs: {len(new_metrics)}")
    lines.append("")

    # 1. Configurations present in both datasets.
    common = sorted(set(old_groups) & set(new_groups))
    only_old = sorted(set(old_groups) - set(new_groups))
    only_new = sorted(set(new_groups) - set(old_groups))

    lines.append("## 1. Configurations compared")
    lines.append("")
    lines.append(f"- Compared: {len(common)}")
    lines.append(f"- Only in pre-audit: {len(only_old)}")
    lines.append(f"- Only in revised: {len(only_new)}")
    lines.append("")

    # 2. Sample size changes.
    lines.append("## 2. Sample size")
    lines.append("")
    lines.append("| Config | Old n | New n | Status |")
    lines.append("|---|---|---|---|")
    under = 0
    for key in common:
        old_n = len(old_groups[key])
        new_n = len(new_groups[key])
        status = "adequate" if new_n >= 10 else "STILL UNDER-SAMPLED"
        if old_n < 10:
            status = "previously under-sampled; " + status
            under += 1
        lines.append(f"| {config_label(key)} | {old_n} | {new_n} | {status} |")
    lines.append("")
    lines.append(f"{under} configurations were previously under-sampled "
                 "(n < 10).")
    lines.append("")

    # 3. Throughput conclusions.
    lines.append("## 3. Throughput conclusions")
    lines.append("")
    lines.append("| Config | Old mean (n) | New mean (n) | Old 95% CI | New 95% CI | Verdict |")
    lines.append("|---|---|---|---|---|---|")
    changed = []
    stable = []
    for key in common:
        old_t = summarize([fnum(m["throughput_req_s"]) for m in old_groups[key]])
        new_t = summarize([fnum(m["throughput_req_s"]) for m in new_groups[key]])
        if old_t["mean"] is None or new_t["mean"] is None:
            continue
        label = config_label(key)
        # Verdict: changed if the new mean is outside the old 95% CI.
        if old_t["ci95_lo"] is not None and (new_t["mean"] < old_t["ci95_lo"] or new_t["mean"] > old_t["ci95_hi"]):
            verdict = "mean moved outside old 95% CI"
            changed.append((label, key))
        else:
            verdict = "stable"
            stable.append((label, key))
        lines.append(f"| {label} | {fmt(old_t['mean'], 0)} ({old_t['n']}) | "
                     f"{fmt(new_t['mean'], 0)} ({new_t['n']}) | "
                     f"{fmt(old_t['ci95_lo'], 0)}–{fmt(old_t['ci95_hi'], 0)} | "
                     f"{fmt(new_t['ci95_lo'], 0)}–{fmt(new_t['ci95_hi'], 0)} | "
                     f"{verdict} |")
    lines.append("")
    lines.append(f"- Throughput conclusions changed: {len(changed)}")
    lines.append(f"- Throughput conclusions stable: {len(stable)}")
    lines.append("")

    # 4. Variance changes.
    lines.append("## 4. Variance changes")
    lines.append("")
    lines.append("| Config | Old SD | New SD | Change |")
    lines.append("|---|---|---|---|")
    for label, key in sorted(changed + stable):
        old_t = summarize([fnum(m["throughput_req_s"]) for m in old_groups[key]])
        new_t = summarize([fnum(m["throughput_req_s"]) for m in new_groups[key]])
        if old_t["sd"] is None or new_t["sd"] is None:
            continue
        ratio = new_t["sd"] / old_t["sd"] if old_t["sd"] else None
        change = "increased" if ratio and ratio > 1.5 else ("decreased" if ratio and ratio < 0.67 else "similar")
        lines.append(f"| {label} | {fmt(old_t['sd'], 0)} | {fmt(new_t['sd'], 0)} | {change} |")
    lines.append("")

    # 5. Election experiment.
    lines.append("## 5. Election experiment")
    lines.append("")
    old_fail = os.path.join(args.old, "failures.json")
    new_fail = os.path.join(args.new, "failures.json")

    def is_election(x):
        # The archived records predate the failure_mode field, so fall back to
        # the run ID there.
        return x.get("failure_mode") == "election" or "election" in x.get("run_id", "")

    def included(x):
        # The revised dataset records the run-selection verdict; the archived
        # one predates it and has no host telemetry to judge, so it is taken
        # as-is.
        return str(x.get("included", "1")) == "1"

    if os.path.exists(old_fail) and os.path.exists(new_fail):
        with open(old_fail) as f:
            old_elec = [x for x in json.load(f) if is_election(x)]
        with open(new_fail) as f:
            new_elec = [x for x in json.load(f) if is_election(x) and included(x)]
        old_x = [x.get("measured_elections") for x in old_elec]
        old_y = [fnum(x.get("write_availability_gap_s_approx")) for x in old_elec]
        new_x = [x.get("measured_elections") for x in new_elec]
        new_y = [fnum(x.get("write_availability_gap_s_approx")) for x in new_elec]
        old_r = labstats.pearson(old_x, old_y)
        new_r = labstats.pearson(new_x, new_y)
        old_p = labstats.pearson_p(old_r, len(old_x)) if old_r is not None else None
        new_p = labstats.pearson_p(new_r, len(new_x)) if new_r is not None else None
        lines.append(f"- Pre-audit: n={len(old_x)}, Pearson r={fmt(old_r, 3)}, p={fmt(old_p, 4)}")
        if old_r is None:
            lines.append("  (not computable: the pre-audit protocol measured "
                         "only the configured target, not the actual number "
                         "of failed elections)")
        lines.append(f"- Revised: n={len(new_x)}, Pearson r={fmt(new_r, 3)}, p={fmt(new_p, 4)}")
        lines.append("")
        # Decoupled recovery metric (revised protocol only; the pre-audit
        # dataset predates it).
        new_rec = [fnum(x.get("recovery_from_isolation_end_s")) for x in new_elec]
        if new_rec and any(v is not None for v in new_rec):
            r_rec = labstats.pearson(new_x, new_rec)
            p_rec = labstats.pearson_p(r_rec, len(new_x)) if r_rec is not None else None
            lines.append(f"- Revised, recovery-from-isolation-end vs measured "
                         f"elections: n={len(new_x)}, Pearson r={fmt(r_rec, 3)}, "
                         f"p={fmt(p_rec, 4)}")
            lines.append("")
            lines.append("The recovery-from-isolation-end metric is decoupled "
                         "from the injection duration (the availability gap "
                         "includes the isolation window, which is proportional "
                         "to the target, so its correlation with the measured "
                         "election count is partly mechanical). If this metric "
                         "is roughly constant across the measured election "
                         "count, the gap correlation is explained by the "
                         "injection mechanism; if it grows, the cluster needs "
                         "extra time to stabilise after many failed elections.")
            lines.append("")
        lines.append("Note: the pre-audit election dataset used the configured "
                     "target as the independent variable (the actual number of "
                     "failed elections was never measured) and ran conditions "
                     "in blocks (target confounded with wall-clock time). The "
                     "revised protocol measures the actual failed elections "
                     "and randomizes condition order. If the correlation "
                     "differs, the difference is reported as a methodology "
                     "change, not as the old result being 'false'.")
        lines.append("")

    # 6. Reliability assessment.
    lines.append("## 6. Reliability of previous results")
    lines.append("")
    lines.append("Previous results are classified as follows:")
    lines.append("")
    lines.append("- **Insufficiently sampled**: n < 10 independent repetitions.")
    lines.append("- **Not independently isolated**: repetitions shared a fixed "
                 "seed (identical workload sequences).")
    lines.append("- **Condition-order confounded**: conditions ran in blocks, "
                 "correlating the treatment with wall-clock time.")
    lines.append("- **Warm-up included in resource metrics**: resource samples "
                 "spanned the whole run, not the measured phase.")
    lines.append("- **Election independent variable unmeasured**: the actual "
                 "number of failed elections was never measured.")
    lines.append("")
    lines.append("These are methodological limitations of the pre-audit "
                 "protocol; they do not by themselves make any particular "
                 "result wrong. A result is reported as 'not reproduced under "
                 "the revised protocol' only when the revised measurements "
                 "differ.")

    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    sys.exit(main())